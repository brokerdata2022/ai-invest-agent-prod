"""
Звʼязок макро-каталізатора з активом — через КАТЕГОРІЮ, не через назву.

## Чому категорія, а не назва

`expectation_synthesis.asset_impacts` містить і `category` (фіксований
перелік, `expectations/synthesize.py:IMPACT_CATEGORIES`), і `assets` —
вільний текст від LLM ("XAU/USD", "золото", "Bitcoin", "S&P 500",
"DXY", "ринок праці"). Парсити вільний текст означає вічно
наздоганяти дрейф формулювань моделі й ламатись від зміни промпта.
Категорій сім, вони фіксовані в коді — мапимо їх статично.

## Головне обмеження цього підходy (чесно, не обійдене)

**Макро-каталізатор НЕ РІЗНИТЬ акції між собою.** Реліз категорії
"ставка" чи "акції" стосується всього ринку одразу — якщо він
підніме всі 215 тикерів зі `screening_results` на однакову величину,
компонент каталізатора для акцій стане КОНСТАНТОЮ, і ранжування
зведеться до тренду з фундаменталом, тобто каталізатор перестане
працювати саме там, де кандидатів найбільше.

Тому розподіл ролей такий:
- для **watchlist-активів** (12 штук: валюти, золото, срібло, нафта,
  газ, кава, BTC/ETH/SOL) макро-реліз САМЕ Є різнителем — різні
  категорії влучають у різні активи, і сам актив є вираженням
  макро-теми;
- для **акцій** різнителем є ТІЛЬКИ новина про конкретний тикер
  (`news_consolidated` уже тегує тикери зі скринінгу — рішення
  2026-09-28) або `news_synthesis` по цьому тикеру. Макро для акцій
  дає спільну "підлогу", а не місце в топі — див.
  `MACRO_FLOOR_FOR_STOCKS` нижче.
- для **крипто-ф'ючерсів** поза watchlist різнителем є власний сетап
  (RSI/OI/funding), який уже порахований `crypto_screening/`.

Це не недоробка, яку треба "виправити ширшою мапою", а властивість
самих даних: щоб макро різнило акції, потрібні сектори/беta до ставки
по кожному тикеру, чого ми не збираємо (SEC EDGAR дає фундаментал, не
класифікацію за секторами).
"""

# Той самий перелік, що expectations/synthesize.py:IMPACT_CATEGORIES.
# Дублюється свідомо (не імпортується): `expectations/` і
# `trading_list/` — незалежні пакети, а зміна переліку в одному з них
# має ламати тест нижче, не тихо змінювати поведінку іншого.
IMPACT_CATEGORIES = (
    "ставка", "економіка", "валюта", "акції", "крипта", "золото", "інший_актив",
)

# Категорія макро-впливу → asset_id watchlist-активів, яких вона
# стосується. asset_id — ті самі, що `watchlist_assets.asset_id`
# (db/schema.sql seed): xauusd, xagusd, wti_crude, brent_crude,
# natgas, coffee, eurusd, usdjpy, btc, eth, sol.
#
# Обґрунтування кожного рядка:
# - "ставка": змінює очікування щодо ФРС/ЄЦБ → валюти (носій різниці
#   ставок), золото (безприбуткова альтернатива), крипта (ризиковий
#   актив, чутливий до ліквідності).
# - "економіка": сила/слабкість економіки → валюти й промислові
#   товари (нафта/газ — попит), не кава (агро, свій цикл).
# - "валюта": прямо валютні пари + золото, бо воно котирується в
#   доларах і рухається проти DXY.
# - "акції": ризиковий апетит → крипта як найчутливіший ризиковий
#   актив; самі акції обробляються окремо (див. MACRO_FLOOR_FOR_STOCKS).
# - "крипта": BTC/ETH/SOL.
# - "золото": золото й срібло (срібло йде за золотом з вищою бетою).
# - "інший_актив": товари.
CATEGORY_TO_WATCHLIST_ASSETS: dict[str, tuple[str, ...]] = {
    "ставка": ("eurusd", "usdjpy", "xauusd", "btc", "eth", "sol"),
    "економіка": ("eurusd", "usdjpy", "wti_crude", "brent_crude", "natgas"),
    "валюта": ("eurusd", "usdjpy", "xauusd"),
    "акції": ("btc", "eth", "sol"),
    "крипта": ("btc", "eth", "sol"),
    "золото": ("xauusd", "xagusd"),
    "інший_актив": ("wti_crude", "brent_crude", "natgas", "coffee"),
}

# Категорії, що дають акціям спільну "підлогу" каталізатора. НЕ
# підіймають конкретний тикер у топ (див. докстрінг модуля) — лише
# позначають, що ринок акцій узагалі в фокусі цього дня. Множник
# нижче свідомо малий: інакше всі 215 тикерів злетіли б разом.
MACRO_FLOOR_FOR_STOCKS = ("ставка", "економіка", "акції")

# Наскільки слабше діє ШИРОКИЙ МАКРО-каталізатор порівняно з
# прицільним (новина/синтез саме про цей актив).
#
# **ЗАСТОСОВУЄТЬСЯ ДО ВСІХ КЛАСІВ АКТИВІВ з 2026-10-13** (було: лише
# до акцій, звідси й стара назва STOCK_MACRO_DAMPING).
#
# Чому змінено — арифметика в одному рядку. Знаменник нормування
# `catalyst_score` це `CATALYST_WEIGHT_RELEASE_HIGH + WEIGHT_NEWS`
# = 1.0 + 0.7 = 1.7. Отже БЕЗ приглушення:
#   - глобальний high-реліз сам дає 1.0/1.7 = **0.59**
#   - власна новина про актив — 0.7/1.7 = **0.41**
# тобто подія, яка НЕ різнить активи, важила більше за ту, яка
# різнить. Для акцій це приглушувалось, для watchlist/крипти/форексу
# — ні.
#
# Живий наслідок (вивід 12 жовтня): `catalyst_score` = 0.647
# ІДЕНТИЧНО для btc, eth, sol, eurusd, xauusd, а `catalyst_summary`
# дослівно однаковий ("initial_jobless_claims вийшов... наш прогноз
# cpi: up"). За всю добу — 2 унікальні значення скору на 10 активів.
# Тобто "фільтр за каталізатором" нічого не фільтрував, і ранжування
# фактично зводилось до `trend_score`.
#
# З приглушенням 0.25 макро дає 0.25/1.7 = 0.147, власна новина —
# 0.41, тобто прицільний каталізатор переважає широкий майже
# утричі. Це і є потрібна властивість: макро-фон позначає, що день
# узагалі в фокусі, а місце в топі актив заробляє власною подією.
MACRO_DAMPING = 0.25

# Стара назва — лишена як псевдонім, щоб не ламати зовнішні імпорти.
STOCK_MACRO_DAMPING = MACRO_DAMPING


def watchlist_assets_for_category(category: str) -> tuple[str, ...]:
    """asset_id watchlist-активів, яких стосується ця категорія.
    Невідома категорія — порожній кортеж, не виняток: перелік
    категорій може розширитись у промпті `expectations/synthesize.py`
    раніше, ніж тут, і це не причина валити весь прогін списку."""
    return CATEGORY_TO_WATCHLIST_ASSETS.get(category, ())


def category_affects_stocks(category: str) -> bool:
    """Чи дає ця категорія акціям спільну 'підлогу' каталізатора."""
    return category in MACRO_FLOOR_FOR_STOCKS


# asset_id → ВЛАСНА категорія активу. Потрібна, щоб відрізнити
# НАПРЯМОК, який стосується самого активу, від напрямку причини.
#
# Живий баг, знайдений прогоном 2026-10-04: усі 10 активів у списку
# отримали позначку `conflicting`, тобто вона перестала щось означати.
# Причина — `asset_impacts` одного релізу містить кілька категорій із
# різними напрямками ("ставка down", "крипта up", "золото up"), і я
# зараховував їх усі як голоси ПРО ЦЕЙ АКТИВ. Але "ставка вниз" для
# солани це ПРИЧИНА, а не напрямок солани; напрямок солани — у
# категорії "крипта".
#
# Тому: напрямок зараховується ЛИШЕ з власної категорії активу. Хіт із
# чужої категорії дає вагу (подія справді стосується активу), але
# напрямок 'neutral' — бо він про інший актив.
NATIVE_CATEGORY_BY_ASSET: dict[str, str] = {
    "xauusd": "золото",
    "xagusd": "золото",
    "eurusd": "валюта",
    "usdjpy": "валюта",
    "btc": "крипта",
    "eth": "крипта",
    "sol": "крипта",
    "wti_crude": "інший_актив",
    "brent_crude": "інший_актив",
    "natgas": "інший_актив",
    "coffee": "інший_актив",
}

# Власна категорія для АКЦІЙ — одна для всіх тикерів: напрямок ринку
# акцій це єдине, що макро-вплив може сказати про конкретний тикер
# (сектора/бету ми не збираємо, див. обмеження вище).
STOCK_NATIVE_CATEGORY = "акції"


def is_native_category(asset_id: str, category: str, is_stock: bool = False) -> bool:
    """Чи цей напрямок стосується САМОГО активу, а не причини."""
    if is_stock:
        return category == STOCK_NATIVE_CATEGORY
    return NATIVE_CATEGORY_BY_ASSET.get(asset_id) == category
