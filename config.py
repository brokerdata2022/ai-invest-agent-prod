# - тренд майже так само важливий — для свінгу вхід проти тренду
#   найдорожча помилка;
# - фундаментал важить, але найменше: він повільний і вже
#   використаний як вхідний фільтр універсуму (Tier A/B/C).
# Для 'intraday' профіль інший: quality → 0, тренд/рух домінують.
