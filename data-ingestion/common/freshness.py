"""
Спільна перевірка актуальності спостереження — БУДНІ дні (Пн-Пт) з
моменту останньої точки, не ПРОСТО календарні (2026-10-04, живий
фідбек користувача: "три дні це багато, дані потрібні останні на
сьогодні якщо ринки відкриті" — фіксований поріг у календарних днях
або занадто м'який на буднях (пропускав дані, застарілі на 2 будні
дні), або занадто суворий на вихідних, карає форекс/товарні джерела
за те, що ринок у суботу/неділю просто ЗАКРИТИЙ, не за реальну
застарілість).

`reporting/watchlist_notify.py` і `analysis/news_analysis/prices.py`
імпортують ОБИДВА — спільний поріг (той самий `common/`-простір, що
вже використовують `common/db.py`/`common/adapter.py`: чисте
обчислення дат, не аналітика конкретного джерела й не бізнес-логіка,
тому rule 1 CLAUDE.md не порушується) замість двох окремих порогів,
які раніше доводилось синхронізувати вручну (живий баг, виявлений
2026-10-04 — числа розійшлись би непомітно).
"""

from datetime import date, timedelta
from typing import Optional

# Скільки БУДНІХ днів публікаційного лагу вважати нормальним — 1 (не
# завжди буквально "сьогодні", бо навіть щоденне джерело типово
# публікує "вчорашнє" закриття вранці наступного буднього дня); понад
# це — ознака, що джерело перестало оновлюватись, не нормальна
# затримка публікації.
STALE_THRESHOLD_BUSINESS_DAYS = 1


def business_days_between(start: date, end: date) -> int:
    """Кількість будніх днів (Пн-Пт) СТРОГО між `start` (виключно) і
    `end` (включно) — вихідні не рахуються як "пропущені" дні
    оновлення, форекс/товарні джерела в них не публікують нічого за
    визначенням. `end <= start` -> 0 (включно "дані з майбутнього",
    чого в нормі не буває, але функція не повинна падати на цьому)."""
    if end <= start:
        return 0
    return sum(
        1
        for offset in range(1, (end - start).days + 1)
        if (start + timedelta(days=offset)).weekday() < 5
    )


def is_stale(
    observed_at: date,
    today: Optional[date] = None,
    threshold_business_days: int = STALE_THRESHOLD_BUSINESS_DAYS,
) -> bool:
    """True, якщо з `observed_at` минуло більше `threshold_business_days`
    БУДНІХ днів до `today` (дефолт — `date.today()`)."""
    today = today if today is not None else date.today()
    return business_days_between(observed_at, today) > threshold_business_days
