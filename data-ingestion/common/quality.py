"""
Перевірка "ревізійної нестабільності" — чи значення ОДНІЄЇ дати
переписувалось між ревізіями на суттєву величину (2026-10-04, живий
кейс xauusd: Twelve Data forex-OTC переписав 2026-09-28 заднім числом
на 81 пункт/~2%, що перевернуло напрямок тижневого синтезу ціни).

Навіщо (живий фідбек користувача: "як я тепер буду розуміти, чи дані
в звіті правильні — кожен раз перевіряти вручну?! сенс з такого
агента"): користувач НЕ повинен вручну звіряти кожне число з
зовнішнім сайтом — це симптом, який агент може й повинен ловити сам,
з уже наявних raw_observations (append-only, rule 6, жодного нового
стовпця схеми не потрібно), і показувати прапорець ПРЯМО у звіті.

Чому це НЕ те саме, що common/freshness.py: freshness — "чи дані
старі" (observed_at далеко від сьогодні); ця перевірка — "чи ЦЕ САМЕ
значення тихо змінювалось заднім числом" — актив може бути ідеально
свіжим (xauusd оновлювався щодня) і водночас нестабільним (значення
вчорашнього дня сьогодні вже інше, ніж було вчора).

**ВИПРАВЛЕНО 2026-10-13: рахуються лише перезаписи ПІСЛЯ закриття
дня.** До цього прапорець висів на 8 з 11 watchlist-активів і через
це нічого не означав. Причина була не в порозі, а у ВИЗНАЧЕННІ: усі
рядки однієї дати порівнювались між собою, незалежно від того, коли
їх забрали. А `crypto_prices` збирає Binance ЩОГОДИНИ, тож для дня D
у БД лежить 24 внутрішньоденні зрізи незакритої свічки — і їхній
розмах це просто ДЕННИЙ ДІАПАЗОН ЦІНИ (живий замір: btc 2026-10-08,
24 рядки, розмах 2.94%), а не переписування історії.

Правильна ознака ревізії: значення дня D змінилось між двома
забираннями, які ОБА відбулись уже після закриття D
(`fetched_at::date > observed_at`). Тоді внутрішньоденний рух не
враховується взагалі, а те, через що перевірка й писалась (Twelve
Data forex-OTC переписав уже закритий 2026-09-28 на ~2% заднім
числом), ловиться так само.

Живий замір після зміни: справжніх постзакритих перезаписів по
watchlist-активах — 0.00-0.63%, тобто жодне джерело зараз історію
суттєво не переписує, і прапорець чесно мовчить. Прапорець, який
спрацьовує завжди, знецінюється — саме тому його й треба було
звузити, а не послабити поріг."""

from decimal import Decimal
from typing import Optional

# % розмах (MAX-MIN)/MIN серед ревізій ОДНІЄЇ дати, вищий за який
# вважаємо це не "шумом округлення", а реальною нестабільністю
# джерела (живий кейс xauusd — 81 пункт/~2%, поріг свідомо нижчий,
# щоб ловити це раніше, до того, як розбіжність стане такою великою).
VOLATILITY_THRESHOLD_PCT = Decimal("1.5")


def has_volatile_recent_revisions(
    conn,
    source: str,
    metric_id: str,
    days: int = 7,
    threshold_pct: Decimal = VOLATILITY_THRESHOLD_PCT,
) -> bool:
    """True, якщо БУДЬ-ЯКА дата за останні `days` днів була переписана
    ПІСЛЯ свого закриття на понад `threshold_pct` — сигнал "це
    джерело непередбачувано змінює вже закриті дні заднім числом"
    (живий кейс xauusd/Twelve Data forex-OTC, 2026-10-04).

    `fetched_at::date > observed_at` — ключова умова (2026-10-13):
    беруться лише ті записи, які забрані вже ПІСЛЯ закінчення дня,
    тож внутрішньоденні зрізи незакритої свічки (Binance щогодини —
    24 рядки на добу) не плутаються з переписуванням історії. Без
    цієї умови прапорець висів на 8 з 11 активів і нічого не
    означав — повне обґрунтування в докстрінгу модуля.

    Менше двох постзакритих записів (HAVING COUNT(*) > 1) —
    порівнювати нема з чим, це не ознака нестабільності."""
    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT MIN(value), MAX(value)
            FROM raw_observations
            WHERE source = %s AND metric_id = %s
              AND observed_at >= now() - (%s || ' days')::interval
              AND fetched_at::date > observed_at
            GROUP BY observed_at
            HAVING COUNT(*) > 1
            """,
            (source, metric_id, days),
        )
        for min_v, max_v in cur.fetchall():
            if min_v and _spread_pct(min_v, max_v) > threshold_pct:
                return True
    return False


def _spread_pct(min_v, max_v) -> Decimal:
    min_v, max_v = Decimal(min_v), Decimal(max_v)
    if min_v == 0:
        return Decimal("0")
    return (max_v - min_v) / min_v * Decimal("100")
